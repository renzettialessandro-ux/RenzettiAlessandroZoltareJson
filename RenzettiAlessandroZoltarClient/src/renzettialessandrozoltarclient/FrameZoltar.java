    private void btnChiediActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnChiediActionPerformed
        String domanda = atxDomanda.getText().trim();

        if (domanda.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Scrivi una domanda!", "Attenzione", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try (java.net.Socket socket = new java.net.Socket("localhost", 5555)) {
            java.io.DataInputStream in = new java.io.DataInputStream(socket.getInputStream());
            java.io.DataOutputStream out = new java.io.DataOutputStream(socket.getOutputStream());

            String personalita = cmbPersonalita.getSelectedItem().toString().toLowerCase();

            out.writeUTF(personalita);
            out.writeUTF(domanda);
            out.flush();

            String risposta = in.readUTF();
            atxRisposta.setText(risposta);

        } catch (Exception ex) {
            atxRisposta.setText("Errore di connessione. Assicurati che il Server sia avviato.");
        }
    }//GEN-LAST:event_btnChiediActionPerformed

